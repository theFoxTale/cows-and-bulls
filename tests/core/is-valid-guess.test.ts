import { describe, it, expect } from 'vitest';
import { isValidGuess } from '@core';

describe('isValidGuess', () => {
  // ------------------------------------------------------------
  // 1. Валидные случаи (все три условия выполнены)
  // ------------------------------------------------------------
  it('принимает корректную догадку для dec (длина 4)', () => {
    expect(isValidGuess('1234', 4, 10)).toBe(true);
  });

  it('принимает корректную догадку для hex (длина 4, нижний регистр)', () => {
    expect(isValidGuess('a3f7', 4, 16)).toBe(true);
  });

  it('принимает корректную догадку для hex (длина 4, верхний регистр)', () => {
    expect(isValidGuess('A3F7', 4, 16)).toBe(true);
  });

  it('принимает корректную догадку для bin (длина 2)', () => {
    expect(isValidGuess('10', 2, 2)).toBe(true);
  });

  it('принимает догадку, начинающуюся с нуля (лидирующий ноль допустим)', () => {
    expect(isValidGuess('0123', 4, 10)).toBe(true);
  });

  // ------------------------------------------------------------
  // 2. Неверная длина
  // ------------------------------------------------------------
  it('отклоняет догадку короче заданной длины', () => {
    expect(isValidGuess('123', 4, 10)).toBe(false);
  });

  it('отклоняет догадку длиннее заданной длины', () => {
    expect(isValidGuess('12345', 4, 10)).toBe(false);
  });

  it('отклоняет пустую строку', () => {
    expect(isValidGuess('', 4, 10)).toBe(false);
  });

  // ------------------------------------------------------------
  // 3. Недопустимые символы для данной системы счисления
  // ------------------------------------------------------------
  it('отклоняет недопустимый символ для dec (буква)', () => {
    expect(isValidGuess('12a4', 4, 10)).toBe(false);
  });

  it('отклоняет недопустимый символ для bin (цифра 2)', () => {
    expect(isValidGuess('12', 2, 2)).toBe(false);
  });

  it('отклоняет недопустимый символ для hex (буква g)', () => {
    expect(isValidGuess('a3g7', 4, 16)).toBe(false);
  });

  it('отклоняет догадку со спецсимволом', () => {
    expect(isValidGuess('12-4', 4, 10)).toBe(false);
  });

  // ------------------------------------------------------------
  // 4. Повторяющиеся цифры
  // ------------------------------------------------------------
  it('отклоняет догадку с повторяющимися цифрами (одинаковый регистр)', () => {
    expect(isValidGuess('1123', 4, 10)).toBe(false);
  });

  it('отклоняет догадку с повторяющимися цифрами (разный регистр для hex)', () => {
    // 'a' и 'A' — одна и та же цифра, поэтому это повтор
    expect(isValidGuess('a3A7', 4, 16)).toBe(false);
  });

  it('отклоняет догадку, состоящую из одной и той же цифры', () => {
    expect(isValidGuess('1111', 4, 10)).toBe(false);
  });

  // ------------------------------------------------------------
  // 5. Комбинированные нарушения (несколько условий сразу)
  // ------------------------------------------------------------
  it('отклоняет догадку с неверной длиной и повторами', () => {
    expect(isValidGuess('112', 4, 10)).toBe(false);
  });

  it('отклоняет догадку с недопустимым символом и повтором', () => {
    expect(isValidGuess('a3a!', 4, 16)).toBe(false);
  });
});
